export function createT(lang) {
  const d = S[lang] || S.en;
  const fb = S.en;
  return function t(key, vars) {
    const path = key.split(".");
    let v = path.reduce((o, k) => (o == null ? o : o[k]), d);
    if (v == null) v = path.reduce((o, k) => (o == null ? o : o[k]), fb);
    if (typeof v !== "string") return v ?? key;
    if (!vars) return v;
    return v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  };
}

export const I18nCtx = createContext({ lang: "en", t: createT("en"), dir: "ltr", locale: "en-US" });
export const useI18n = () => useContext(I18nCtx);

/** שמות ימים ותאריכים מגיעים מ-Intl, לא מטבלה ידנית */
export function makeDates(locale) {
  const wd = new Intl.DateTimeFormat(locale, { weekday: "long" });
  const wdShort = new Intl.DateTimeFormat(locale, { weekday: "narrow" });
  const md = new Intl.DateTimeFormat(locale, { day: "numeric", month: "numeric" });
  return {
    weekday: (d) => wd.format(d),
    weekdayShort: (d) => wdShort.format(d),
    dayMonth: (d) => md.format(d),
  };
}
