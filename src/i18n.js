export const LANG_BY = Object.fromEntries(LANGS.map((l) => [l.code, l]));

export function detectLang() {
  try {
    const saved = localStorage.getItem("wx-lang");
    if (saved && LANG_BY[saved]) return saved;
  } catch { /* private mode */ }
  const nav = (typeof navigator !== "undefined" && navigator.languages) || [];
  for (const tag of nav) {
    const base = String(tag).slice(0, 2).toLowerCase();
    if (LANG_BY[base]) return base;
  }
  return "en";
}

